// vrt-egress system worker entrypoint (Phase 1 T6).
//
// Every tenant worker's `fetch()` — and, on workerd builds that route
// sockets through it, `connect()` — is delivered to this entrypoint via
// `globalOutbound`. The worker is defense layer 3 of the egress stack:
//
//   layer 1  workerd `outbound-network` allow=["public"], deny
//            private/local/unix — filters the resolved IP at dial time
//            (post-resolution filtering VERIFIED 2026-11-17 on our
//            workerd build: connect() to resolved private addresses is
//            refused by restrictPeers() — see
//            doc/platform/workers-runtime-egress.md for the method).
//   layer 2  Pod NetworkPolicy generated by vrt-config::netpolicy —
//            denies private CIDRs outright, allows DNS/kube-dns, the
//            platform backends, and public space only.
//   layer 3  this worker — URL/policy check, internal-header stripping,
//            redirect=manual pass-through.
//
// The policy arrives as canonical JSON in the VRT_EGRESS_POLICY text
// binding rendered by vrt-config. Anything absent, malformed, or
// carrying unexpected fields fails closed: every fetch is denied.
import { WorkerEntrypoint } from "cloudflare:workers";
// MIG-14: the egress worker's own connect() — it dials through its
// own `globalOutbound` (`outbound-network`), whose restrictPeers()
// validates the RESOLVED address at connect time (verified on our
// workerd build). Passing the hostname — never a pre-resolved IP —
// means validation and dialing act on the same resolution result:
// no resolve-then-dial window for DNS rebinding.
import { connect as upstreamConnect } from "cloudflare:sockets";
import {
  evaluateTarget,
  evaluateTcpTarget,
  parseEgressPolicy,
  type EgressPolicy,
  type TcpTarget,
} from "./policy.js";
