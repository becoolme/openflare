function denied(code: string, detail?: string): Response {
  const body = JSON.stringify({
    error: "EGRESS_DENIED",
    code,
    ...(detail === undefined ? {} : { detail }),
  });
  return new Response(body, {
    status: 403,
    headers: {
      "content-type": "application/json",
      "cache-control": "no-store",
      [DENIED_HEADER]: code,
    },
  });
}

function upstreamError(): Response {
  return new Response(JSON.stringify({ error: "EGRESS_UPSTREAM" }), {
    status: 502,
    headers: {
      "content-type": "application/json",
      "cache-control": "no-store",
      [ERROR_HEADER]: "upstream",
    },
  });
}

// MIG-14: the inbound CONNECT socket's structural shape — same fields
// as the upstream socket `upstreamConnect` returns. The inbound CONNECT
// socket exposes NO address properties: the requested `host:port`
// authority arrives only as `(await socket.opened).localAddress`
// (verified on workerd 1.20260916.1; `socket.localAddress` is undefined).
interface TcpSocket {
  readable: ReadableStream;
  writable: WritableStream;
  opened?: Promise<unknown>;
  close?: () => unknown;
}

// Per-isolate concurrency bound. A WorkerEntrypoint instance is
// per-event, so the counter lives at module scope; the CONNECT event
// carries no tenant identity, making the isolate the only enforceable
// granularity anyway. Slow connections cannot exhaust the isolate's
// sockets without tripping `tcpMaxConcurrent` first.
//
// Slots are tracked as sessions, not a bare counter, because workerd
// CANCELS the handler's IoContext when the tenant closes its socket
// first (verified on workerd 1.20260916.1: no timer fires and no
// `finally` runs afterwards). A counter decremented in `finally` would
// then leak one slot per tenant-initiated close and wedge the isolate
// at `concurrent_limit`. Every session carries the latest time its
// own deadline could still fire; `reapAbandonedTcp` drops (and logs)
// sessions past it — a live handler always ends itself by then.
interface TcpSession {
  port: number;
  started: number;
  lastActivity: number;
  /** Longest a live handler can stay silent before ending itself. */
  silenceBudgetMs: number;
  counters: { up: number; down: number };
}
const activeTcpSessions = new Set<TcpSession>();

// Slack over the idle/connect timer for timer tick granularity and
// scheduling jitter before a silent session is declared abandoned.
const REAP_GRACE_MS = 1_000;

/** Drop sessions whose handler can no longer be running; log each. */
function reapAbandonedTcp(now: number): void {
  for (const sess of activeTcpSessions) {
    if (now - sess.lastActivity > sess.silenceBudgetMs + REAP_GRACE_MS) {
      activeTcpSessions.delete(sess);
      logTcpClose(
        sess.port,
        sess.counters.up,
        sess.counters.down,
        sess.lastActivity - sess.started,
        "abandoned",
      );
    }
  }
}

// Bound on waiting for the CONNECT socket's `opened` info. workerd
// resolves it immediately for inbound CONNECT; a hang means the
// platform contract broke, so fail closed rather than wait forever.
const OPENED_WAIT_MS = 5_000;

/** The CONNECT authority from `socket.opened`, or null (fail closed). */
async function connectAuthority(s: TcpSocket | undefined): Promise<unknown> {
  if (s === undefined || s === null || s.opened === undefined) return null;
  try {
    const info = await Promise.race([
      s.opened as Promise<{ localAddress?: unknown } | null | undefined>,
      sleep(OPENED_WAIT_MS).then(() => null),
    ]);
    return info?.localAddress ?? null;
  } catch {
    return null;
  }
}

/**
 * MIG-15 r2: preamble encoders keyed by the typed `kind` on
 * `internalTcpTargets` entries — adding a protocol is a table entry
 * here, never a pg-specific branch in the relay path. `"pg-v1"`:
 * first host label = platform-minted binding id, emitted as one
 * `VRT-PG1 <id>` line the proxy reads exactly once.
 */
const INTERNAL_TCP_PREAMBLES: Record<
  string,
  (host: string) => Uint8Array
> = {
  "pg-v1": (host) =>
    new TextEncoder().encode(`VRT-PG1 ${host.split(".")[0] ?? ""}\n`),
};

const sleep = (ms: number): Promise<void> =>
  new Promise((resolve) => setTimeout(resolve, ms));

/**
 * Bidirectional byte relay between the inbound tenant socket and the
 * upstream socket. Returns the close reason: "eof" (clean end in the
 * down direction or after a clean half-close), "error" (either pipe
 * died), or "idle_timeout" (no bytes in either direction for
 * `idleMs`). A clean tenant FIN ("up_end") is NOT teardown — the
 * server may still answer (WHOIS sends its record, then closes), so
 * the down pipe runs until it ends or the connection idles. Teardown
 * closes `upstream`, settling whichever pipe lost the race; nothing
 * outlives the handler.
 */
async function pumpTcp(
  inbound: TcpSocket,
  upstream: TcpSocket,
  idleMs: number,
  counters: { up: number; down: number },
  session: TcpSession,
): Promise<string> {
  let lastActivity = Date.now();
  session.lastActivity = lastActivity;
  session.silenceBudgetMs = idleMs;
  const meter = (dir: "up" | "down") =>
    new TransformStream<Uint8Array, Uint8Array>({
      transform(chunk, controller) {
        counters[dir] += chunk?.byteLength ?? 0;
        lastActivity = Date.now();
        session.lastActivity = lastActivity;
        controller.enqueue(chunk);
      },
    });
  const upDone = inbound.readable
    .pipeThrough(meter("up"))
    .pipeTo(upstream.writable)
    .then(() => "up_end" as const, () => "up_err" as const);
  const downDone = upstream.readable
    .pipeThrough(meter("down"))
    .pipeTo(inbound.writable)
    .then(() => "down_end" as const, () => "down_err" as const);
  let finished = false;
  let finishNow: () => void = () => {};
  const finishSignal = new Promise<void>((resolve) => {
    finishNow = resolve;
  });
  const tick = Math.max(50, Math.min(500, Math.floor(idleMs / 4)));
  const idleWatch = (async () => {
    while (!finished) {
      await Promise.race([sleep(tick), finishSignal]);
      if (finished) return "watch_end" as const;
      if (Date.now() - lastActivity >= idleMs) return "idle" as const;
    }
    return "watch_end" as const;
  })();
  let reason: string;
  const first = await Promise.race([downDone, upDone, idleWatch]);
  if (first === "idle") {
    reason = "idle_timeout";
  } else if (first === "down_end") {
    reason = "eof";
  } else if (first === "up_end") {
    const second = await Promise.race([downDone, idleWatch]);
    reason =
      second === "idle"
        ? "idle_timeout"
        : second === "down_err"
          ? "error"
          : "eof";
  } else {
    reason = "error";
  }
  finished = true;
  finishNow();
  // Severing upstream settles the surviving pipe's far end; severing
  // the inbound socket settles the near end (real socket.close()
  // aborts both streams, and workerd closes it on return anyway).
  // Collecting both — already rejection-wrapped — plus the watcher
  // leaves nothing unhandled past the connection's lifetime.
  await closeQuietly(upstream);
  await closeQuietly(inbound);
  await Promise.allSettled([upDone, downDone, idleWatch]);
  return reason;
}

export class EgressProxy extends WorkerEntrypoint {
  readonly #policy: EgressPolicy | null;
  readonly #env: unknown;

  constructor(ctx: unknown, env: unknown) {
    super(ctx, env);
    this.#env = env;
    const raw = (env as Record<string, unknown> | undefined)?.[POLICY_BINDING];
    this.#policy = parseEgressPolicy(raw);
  }

  async fetch(request: Request): Promise<Response> {
    const decision = evaluateTarget(request.url, this.#policy);
    if (!decision.allow) return denied(decision.code, decision.detail);
    let upstream: Response;
    const started = Date.now();
    try {
      upstream = await fetch(request, {
        headers: stripInternalHeaders(request.headers),
        // Never follow redirects ourselves — `manual` hands the 3xx back
        // to the tenant worker, whose next fetch re-runs the full policy.
        // A redirect therefore cannot smuggle a request to a denied
        // address.
        redirect: "manual",
        signal: AbortSignal.timeout(this.#policy.requestTimeoutMs),
      });
    } catch (e) {
      // MIG-10: the error is classified + logged (host/port/duration —
      // never path/query/userinfo), then THROWN back at the tenant.
      // On Cloudflare an unreachable upstream rejects fetch(); tenant
      // code wraps it in try/catch for fallback — a synthetic 502
      // would silently defeat that pattern. workerd propagates a
      // globalOutbound entrypoint's throw as a subrequest rejection
      // (same mechanism as a throwing service binding).
      const cls = classifyUpstreamError(e);
      logUpstreamError(cls, request.url, Date.now() - started, e);
      throw upstreamFetchError(cls);
    }
    if (upstream.status === 101) {
      // WebSocket upgrade: the `webSocket` property must be re-attached
      // to a rebuilt Response so upstream headers can be re-stripped —
      // a hostile host must not smuggle x-vrt-*/x-open-compute-* back
      // at the tenant.
      const webSocket = (upstream as { webSocket?: unknown }).webSocket;
      if (webSocket === undefined || webSocket === null) {
        return upstreamError();
      }
      try {
        return new Response(null, {
          status: 101,
          headers: stripInternalHeaders(upstream.headers),
          webSocket,
        } as ResponseInit);
      } catch {
        // Plain undici (node --test) rejects 101 responses; workerd's
        // Response accepts them. Fail closed either way.
        return upstreamError();
      }
    }
    // IMG2: `cf.image` — the tenant's cf blob arrives whole on
    // `request.cf` via the subrequest channel; transform the upstream
    // body through facade-images exactly like the env.IMAGES binding.
    // Failure shape mirrors CF: `cf-resized: err=<code>` + ERROR body —
    // never a silently untransformed image.
    const plan = cfImagePlan(request);
    if (plan !== undefined) {
      return this.#transformImage(request, upstream, plan);
    }
    return new Response(upstream.body, {
      status: upstream.status,
      statusText: upstream.statusText,
      headers: stripInternalHeaders(upstream.headers),
    });
  }

  /** POST the upstream body to facade-images over the service binding. */
  async #transformImage(
    request: Request,
    upstream: Response,
    plan: CfImagePlan,
  ): Promise<Response> {
    const url = new URL(request.url);
    const redirect = () =>
      new Response(null, {
        status: 302,
        headers: { location: url.toString() },
      });
    const svc = (this.#env as Record<string, unknown>)?.["VRT_IMAGES"] as
      | { fetch(input: string, init?: RequestInit): Promise<Response> }
      | undefined;
    if (svc === undefined || typeof svc.fetch !== "function") {
      return new Response(`ERROR 9490\n`, {
        status: 500,
        headers: { "content-type": "text/plain", "cf-resized": "err=9490" },
      });
    }
    let out: Response;
    try {
      const src = new Uint8Array(await upstream.arrayBuffer());
      if (src.length > SRC_MAX) {
        return new Response("ERROR 9424\n", {
          status: 413,
          headers: { "content-type": "text/plain", "cf-resized": "err=9424" },
        });
      }
      // SVG sources are never transformed upstream — svg-hush sanitizes
      // and passes them through as image/svg+xml with every plan option
      // (including format:"json") ignored. Malformed markup is a
      // source-level error: ERROR 9420, honoring onerror:"redirect"
      // like the transform error paths below.
      if (sniffSvg(src)) {
        try {
          return new Response(hushFilter(src), {
            headers: { "content-type": "image/svg+xml" },
          });
        } catch (e) {
          if (!(e instanceof HushError)) throw e;
          if (plan.onerrorRedirect) return redirect();
          return new Response("ERROR 9420\n", {
            status: 415,
            headers: {
              "content-type": "text/plain",
              "cf-resized": "err=9420",
            },
          });
        }
      }
      // Draw payloads are fetched here — the egress worker is the only
      // layer that can reach tenant-specified URLs, and each fetch
      // re-runs the egress policy like the source URL did. Image-entry
      // bytes ride to the facade as `draw_image` fields, text-entry
      // font bytes as `draw_font` (paired with the entry's draw_text
      // spec); indices line up with the per-entry ops in
      // plan.transforms. A payload that cannot be fetched is a
      // source-level failure: ERROR 9420 (unfetchable image),
      // honoring onerror:"redirect" like the other transform error
      // paths.
      const payloads: Uint8Array[] = [];
      for (const draw of plan.draws) {
        const url = draw.kind === "text" ? draw.fontUrl : draw.url;
        let bytes: Uint8Array | undefined;
        if (evaluateTarget(url, this.#policy).allow) {
          try {
            const resp = await fetch(url, {
              signal: AbortSignal.timeout(
                this.#policy?.requestTimeoutMs ?? 30_000,
              ),
            });
            const buf = new Uint8Array(await resp.arrayBuffer());
            if (buf.length > SRC_MAX) {
              if (plan.onerrorRedirect) return redirect();
              return new Response("ERROR 9424\n", {
                status: 413,
                headers: {
                  "content-type": "text/plain",
                  "cf-resized": "err=9424",
                },
              });
            }
            bytes = buf;
          } catch {
            bytes = undefined;
          }
        }
        if (bytes === undefined) {
          if (plan.onerrorRedirect) return redirect();
          return new Response("ERROR 9420\n", {
            status: 502,
            headers: {
              "content-type": "text/plain",
              "cf-resized": "err=9420",
            },
          });
        }
        payloads.push(bytes);
      }
      out = await svc.fetch("http://vrt-images.internal/transform", {
        method: "POST",
        body: cfImageBody(src, plan, payloads),
      });
    } catch {
      // Transport-level failure to the facade — CF surfaces these as
      // err=9523 through cf-resized too.
      if (plan.onerrorRedirect) return redirect();
      return new Response("ERROR 9523\n", {
        status: 500,
        headers: { "content-type": "text/plain", "cf-resized": "err=9523" },
      });
    }
    const err = out.headers.get("cf-images-binding");
    if (err !== null) {
      const code = /^err=\d+$/.test(err) ? err.slice(4) : "9523";
      if (plan.onerrorRedirect) return redirect();
      return new Response(`ERROR ${code}\n`, {
        status: out.status,
        headers: {
          "content-type": "text/plain",
          "cf-resized": `err=${code}`,
        },
      });
    }
    if (plan.json) {
      // `format:"json"` reports the TRANSFORMED result's metadata —
      // sniff the encoded bytes rather than trusting op intent.
      const bytes = new Uint8Array(await out.arrayBuffer());
      const info = sniffImage(bytes);
      return new Response(
        JSON.stringify({
          width: info?.width ?? 0,
          height: info?.height ?? 0,
          // CF reports the full mime (`image/jpeg`), not the short name.
          format: info ? `image/${info.format}` : "unknown",
          size: bytes.length,
        }),
        { headers: { "content-type": "application/json" } },
      );
    }
    const headers = stripInternalHeaders(out.headers);
    headers.delete("content-length");
    return new Response(out.body, { status: out.status, headers });
  }

  // MIG-14: controlled raw-TCP forwarding. workerd VERIFIED to deliver
  // the tenant's `cloudflare:sockets` connect() here as an HTTP CONNECT
  // through the tenant's globalOutbound (see
  // doc/platform/workers-runtime-egress.md §6 for the mechanism and the
  // real-workerd evidence): the requested "host:port" authority is
  // `(await socket.opened).localAddress` — the socket object itself has
  // no address properties, and `remoteAddress` is absent.
  //
  // The handler's returned promise is the connection's lifetime:
  // workerd keeps the socket open until it resolves and severs it on a
  // throw. Denials close the socket then throw `EGRESS_DENIED` with a
  // stable denyCode (port / ip_* / denied_name / unqualified /
  // concurrent_limit / connect_timeout / idle_timeout); upstream dial
  // failures throw the same EGRESS_UPSTREAM shape fetch uses.
  //
  // secureTransport: workerd rejects `useTls` upstream of this handler
  // ("Incoming CONNECT with TLS not supported") — a typed refusal, not
  // a silent plaintext downgrade. `starttls` upgrades on the TENANT
  // side, so the relay just carries ciphertext — transparent support.
  async connect(socket: unknown): Promise<void> {
    const s = socket as TcpSocket;
    // Reap first so even a denied connect() settles stale accounting.
    reapAbandonedTcp(Date.now());
    const decision = evaluateTcpTarget(await connectAuthority(s), this.#policy);
    if (!decision.allow) {
      logTcpDeny(decision.port, decision.code);
      await closeQuietly(s);
      throw tcpDenied(decision.code, decision.detail);
    }
    const policy = this.#policy as EgressPolicy;
    const target = decision.target as TcpTarget;
    const internal = decision.internal;
    if (activeTcpSessions.size >= policy.tcpMaxConcurrent) {
      logTcpDeny(target.port, "concurrent_limit");
      await closeQuietly(s);
      throw tcpDenied("concurrent_limit");
    }
    const started = Date.now();
    const counters = { up: 0, down: 0 };
    const session: TcpSession = {
      port: target.port,
      started,
      lastActivity: started,
      // Dial phase: bounded by the connect timer; pumpTcp narrows it
      // to the idle timer once bytes can flow.
      silenceBudgetMs: policy.tcpConnectTimeoutMs,
      counters,
    };
    activeTcpSessions.add(session);
    let upstream: TcpSocket | null = null;
    let reason = "eof";
    try {
      try {
        if (internal !== undefined) {
          // MIG-15: typed internal TCP target provider — the dial goes
          // through the INTERNAL_NET service binding (loopback-only
          // internal-network), never `outbound-network`, so public
          // egress rules stay untouched. The binding is present only
          // when platform render emitted internal targets.
          const svc = (this.#env as Record<string, unknown>)?.["INTERNAL_NET"] as
            | { connect?: (addr: { hostname: string; port: number }) => TcpSocket }
            | undefined;
          if (svc === undefined || typeof svc.connect !== "function") {
            reason = "config";
            throw tcpDenied("config");
          }
          upstream = svc.connect({
            hostname: internal.upstreamHost,
            port: internal.upstreamPort,
          });
        } else {
          upstream = upstreamConnect({
            hostname: target.dialHost,
            port: target.port,
          });
        }
      } catch (e) {
        if (reason === "config") throw e;
        const cls = classifyUpstreamError(e);
        reason = cls;
        throw upstreamFetchError(cls);
      }
      let dialError: unknown;
      const opened = await Promise.race([
        (upstream.opened as Promise<unknown>).then(
          () => "opened" as const,
          (e: unknown) => {
            dialError = e;
            return "failed" as const;
          },
        ),
        sleep(policy.tcpConnectTimeoutMs).then(() => "timeout" as const),
      ]);
      if (opened === "timeout") {
        reason = "connect_timeout";
        throw tcpDenied("connect_timeout");
      }
      if (opened === "failed") {
        const cls = classifyUpstreamError(dialError);
        reason = cls;
        throw upstreamFetchError(cls);
      }
      if (internal !== undefined && upstream !== null) {
        // Identity preamble written by THIS worker before any tenant
        // byte is relayed — the encoder is selected by the typed
        // `kind` (unknown → fail closed; parse already rejects it).
        const encode = INTERNAL_TCP_PREAMBLES[internal.kind];
        if (encode === undefined) throw tcpDenied("config");
        try {
          const w = (upstream.writable as WritableStream).getWriter();
          await w.write(encode(target.host));
          w.releaseLock();
        } catch (e) {
          const cls = classifyUpstreamError(e);
          reason = cls;
          throw upstreamFetchError(cls);
        }
      }
      reason = await pumpTcp(s, upstream, policy.tcpIdleTimeoutMs, counters, session);
      if (reason === "idle_timeout") throw tcpDenied("idle_timeout");
    } finally {
      const ours = activeTcpSessions.delete(session);
      // The inbound socket is closed by workerd on return; closing it
      // here too settles a tenant that half-closed and walked away.
      if (upstream !== null) await closeQuietly(upstream);
      await closeQuietly(s);
      // A reaped session already logged its close as "abandoned".
      if (ours) {
        logTcpClose(target.port, counters.up, counters.down, Date.now() - started, reason);
      }
    }
  }
}
export default EgressProxy;
